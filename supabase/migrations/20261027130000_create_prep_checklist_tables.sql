-- AI preparation checklist tables.
-- RLS is intentionally disabled per the requested setup. With the frontend
-- using the Supabase anon key directly, these tables may be publicly accessible.

create table if not exists public.prep_items (
  id bigint generated by default as identity primary key,
  scheduleid bigint not null references public.confirmed_schedules (id) on delete cascade,
  roomid bigint not null,
  name text not null,
  emoji text,
  kind text not null check (kind in ('personal', 'shared')),
  neededcount integer not null default 1 check (neededcount >= 1),
  memo text,
  reason text,
  source text not null default 'manual' check (source in ('ai', 'manual')),
  createdby text,
  createdbytype text check (createdbytype in ('member', 'guest')),
  sortorder integer not null default 0,
  createdat timestamptz not null default now()
);

create index if not exists prep_items_scheduleid_sortorder_idx
  on public.prep_items (scheduleid, sortorder, id);

create table if not exists public.prep_assignments (
  id bigint generated by default as identity primary key,
  itemid bigint not null references public.prep_items (id) on delete cascade,
  memberid text not null,
  membertype text not null check (membertype in ('member', 'guest')),
  note text check (note is null or char_length(note) <= 30),
  status text not null default 'assigned' check (status in ('assigned', 'requested')),
  requestedby text,
  requestedbytype text check (requestedbytype in ('member', 'guest')),
  isdone boolean not null default false,
  doneat timestamptz,
  createdat timestamptz not null default now(),
  unique (itemid, membertype, memberid)
);

create index if not exists prep_assignments_itemid_status_idx
  on public.prep_assignments (itemid, status);

create index if not exists prep_assignments_member_idx
  on public.prep_assignments (membertype, memberid);

create table if not exists public.prep_checks (
  id bigint generated by default as identity primary key,
  itemid bigint not null references public.prep_items (id) on delete cascade,
  memberid text not null,
  membertype text not null check (membertype in ('member', 'guest')),
  checked boolean not null default false,
  updatedat timestamptz not null default now(),
  unique (itemid, membertype, memberid)
);

create index if not exists prep_checks_member_idx
  on public.prep_checks (membertype, memberid);

alter table public.prep_items disable row level security;
alter table public.prep_assignments disable row level security;
alter table public.prep_checks disable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'prep_items'
  ) then
    alter publication supabase_realtime add table public.prep_items;
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'prep_assignments'
  ) then
    alter publication supabase_realtime add table public.prep_assignments;
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'prep_checks'
  ) then
    alter publication supabase_realtime add table public.prep_checks;
  end if;
end
$$;
