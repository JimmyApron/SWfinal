-- 비용 정산 (영수증 OCR)
--
-- 보안 구조
--   * 이 앱은 게스트가 Supabase 로그인 없이 쓰기 때문에, anon 키로는 "그 방 사람"과 "외부인"을
--     DB가 구분할 수 없다. 그래서 정산 테이블과 증빙 버킷은 RLS를 켠 채 정책을 하나도 만들지
--     않아 anon/authenticated 접근을 전부 막고, 백엔드(service role 키)만 읽고 쓴다.
--   * 방 멤버/게스트 확인은 백엔드 라우트에서 한다. (backend/.env 의 SUPABASE_SERVICE_ROLE_KEY 필요)
--   * 저장 RPC 도 service_role 만 실행할 수 있다.

-- ---------------------------------------------------------------------------
-- 1) 지출
-- ---------------------------------------------------------------------------
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  scheduleid bigint not null references public.confirmed_schedules (id) on delete cascade,
  roomid bigint not null,
  title text not null,
  amount integer not null check (amount > 0),
  paidat timestamptz,
  payerid text not null,
  payertype text not null check (payertype in ('member', 'guest')),
  bankname text,
  accountnumber text,                       -- 전체 번호. 목록/카드에는 백엔드가 마스킹해서 내려준다.
  splitmode text not null default 'equal' check (splitmode in ('equal', 'custom')),
  receiptpath text,                         -- receipts 버킷 안의 경로
  ocrraw jsonb,                             -- OCR 응답 원본 (디버깅용)
  source text not null default 'manual' check (source in ('manual', 'ocr')),
  createdby text not null,
  createdbytype text not null check (createdbytype in ('member', 'guest')),
  createdat timestamptz not null default now(),
  updatedat timestamptz not null default now(),
  isdeleted boolean not null default false
);

create index if not exists expenses_scheduleid_idx
  on public.expenses (scheduleid, paidat)
  where isdeleted = false;

create index if not exists expenses_roomid_idx
  on public.expenses (roomid)
  where isdeleted = false;

-- ---------------------------------------------------------------------------
-- 2) 참여자별 부담 금액
-- ---------------------------------------------------------------------------
create table if not exists public.expense_shares (
  id bigint generated by default as identity primary key,
  expenseid bigint not null references public.expenses (id) on delete cascade,
  memberid text not null,
  membertype text not null check (membertype in ('member', 'guest')),
  amount integer not null check (amount >= 0),
  sentat timestamptz,                       -- 참여자가 "보냈어요"를 누른 시각
  confirmedat timestamptz,                  -- 결제자가 "받았어요"를 누른 시각 (선택)
  unique (expenseid, membertype, memberid)
);

create index if not exists expense_shares_expenseid_idx
  on public.expense_shares (expenseid);

create index if not exists expense_shares_member_idx
  on public.expense_shares (membertype, memberid);

-- ---------------------------------------------------------------------------
-- 3) 내 계좌 저장 (회원 전용. profiles 는 anon 으로 읽혀서 쓰지 않는다)
-- ---------------------------------------------------------------------------
create table if not exists public.user_payment_accounts (
  userid uuid primary key references auth.users (id) on delete cascade,
  bankname text,
  accountnumber text,
  updatedat timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 4) RLS: 켜기만 하고 정책은 만들지 않는다 (service role 만 접근)
-- ---------------------------------------------------------------------------
alter table public.expenses enable row level security;
alter table public.expense_shares enable row level security;
alter table public.user_payment_accounts enable row level security;

-- ---------------------------------------------------------------------------
-- 5) 저장 RPC (expenses + expense_shares 를 한 트랜잭션으로)
-- ---------------------------------------------------------------------------
create or replace function public.assert_room_participant(
  p_room bigint,
  p_id text,
  p_type text
) returns void
language plpgsql
as $$
begin
  if p_type = 'member' then
    if not exists (
      select 1 from public.room_members where roomid = p_room and userid::text = p_id
    ) then
      raise exception 'not a member of the room: %', p_id;
    end if;
  elsif p_type = 'guest' then
    if not exists (
      select 1 from public.room_guests where roomid = p_room and id::text = p_id
    ) then
      raise exception 'not a guest of the room: %', p_id;
    end if;
  else
    raise exception 'invalid participant type: %', p_type;
  end if;
end;
$$;

-- payload 예:
-- { "scheduleid": 1, "roomid": 2, "title": "서면 파스타하우스", "amount": 10001,
--   "paidat": "2026-10-24T18:30:00+09:00", "payerid": "...", "payertype": "member",
--   "bankname": "토스뱅크", "accountnumber": "1000...", "splitmode": "equal",
--   "receiptpath": null, "ocrraw": null, "source": "ocr",
--   "createdby": "...", "createdbytype": "member",
--   "shares": [ { "memberid": "...", "membertype": "member", "amount": 3334 }, ... ] }
create or replace function public.create_expense(payload jsonb)
returns bigint
language plpgsql
as $$
declare
  v_schedule bigint := (payload ->> 'scheduleid')::bigint;
  v_room bigint := (payload ->> 'roomid')::bigint;
  v_amount integer := (payload ->> 'amount')::integer;
  v_share jsonb;
  v_sum bigint := 0;
  v_expense_id bigint;
begin
  if not exists (
    select 1 from public.confirmed_schedules where id = v_schedule and roomid = v_room
  ) then
    raise exception 'schedule % does not belong to room %', v_schedule, v_room;
  end if;

  if v_amount is null or v_amount <= 0 then
    raise exception 'amount must be a positive integer';
  end if;

  if jsonb_typeof(payload -> 'shares') is distinct from 'array'
     or jsonb_array_length(payload -> 'shares') = 0 then
    raise exception 'at least one share is required';
  end if;

  perform public.assert_room_participant(v_room, payload ->> 'payerid', payload ->> 'payertype');
  perform public.assert_room_participant(v_room, payload ->> 'createdby', payload ->> 'createdbytype');

  for v_share in select * from jsonb_array_elements(payload -> 'shares') loop
    perform public.assert_room_participant(v_room, v_share ->> 'memberid', v_share ->> 'membertype');
    v_sum := v_sum + (v_share ->> 'amount')::integer;
  end loop;

  if v_sum <> v_amount then
    raise exception 'shares total (%) does not match amount (%)', v_sum, v_amount;
  end if;

  insert into public.expenses (
    scheduleid, roomid, title, amount, paidat, payerid, payertype,
    bankname, accountnumber, splitmode, receiptpath, ocrraw, source,
    createdby, createdbytype
  ) values (
    v_schedule, v_room, payload ->> 'title', v_amount,
    nullif(payload ->> 'paidat', '')::timestamptz,
    payload ->> 'payerid', payload ->> 'payertype',
    nullif(payload ->> 'bankname', ''), nullif(payload ->> 'accountnumber', ''),
    coalesce(payload ->> 'splitmode', 'equal'),
    nullif(payload ->> 'receiptpath', ''),
    case when jsonb_typeof(payload -> 'ocrraw') = 'null' then null else payload -> 'ocrraw' end,
    coalesce(payload ->> 'source', 'manual'),
    payload ->> 'createdby', payload ->> 'createdbytype'
  ) returning id into v_expense_id;

  insert into public.expense_shares (expenseid, memberid, membertype, amount)
  select v_expense_id, s ->> 'memberid', s ->> 'membertype', (s ->> 'amount')::integer
  from jsonb_array_elements(payload -> 'shares') s;

  return v_expense_id;
end;
$$;

-- 수정: 같은 payload 형식. 금액이 그대로인 참여자의 "보냈어요/받았어요" 기록은 유지한다.
create or replace function public.update_expense(p_expenseid bigint, payload jsonb)
returns void
language plpgsql
as $$
declare
  v_expense public.expenses%rowtype;
  v_amount integer := (payload ->> 'amount')::integer;
  v_share jsonb;
  v_sum bigint := 0;
  v_old jsonb;
begin
  select * into v_expense from public.expenses where id = p_expenseid and isdeleted = false;
  if not found then
    raise exception 'expense % not found', p_expenseid;
  end if;

  if v_amount is null or v_amount <= 0 then
    raise exception 'amount must be a positive integer';
  end if;

  if jsonb_typeof(payload -> 'shares') is distinct from 'array'
     or jsonb_array_length(payload -> 'shares') = 0 then
    raise exception 'at least one share is required';
  end if;

  perform public.assert_room_participant(v_expense.roomid, payload ->> 'payerid', payload ->> 'payertype');

  for v_share in select * from jsonb_array_elements(payload -> 'shares') loop
    perform public.assert_room_participant(
      v_expense.roomid, v_share ->> 'memberid', v_share ->> 'membertype'
    );
    v_sum := v_sum + (v_share ->> 'amount')::integer;
  end loop;

  if v_sum <> v_amount then
    raise exception 'shares total (%) does not match amount (%)', v_sum, v_amount;
  end if;

  select coalesce(jsonb_agg(to_jsonb(o)), '[]'::jsonb) into v_old
  from public.expense_shares o where o.expenseid = p_expenseid;

  update public.expenses set
    title = payload ->> 'title',
    amount = v_amount,
    paidat = nullif(payload ->> 'paidat', '')::timestamptz,
    payerid = payload ->> 'payerid',
    payertype = payload ->> 'payertype',
    bankname = nullif(payload ->> 'bankname', ''),
    accountnumber = nullif(payload ->> 'accountnumber', ''),
    splitmode = coalesce(payload ->> 'splitmode', splitmode),
    receiptpath = case
      when payload ? 'receiptpath' then nullif(payload ->> 'receiptpath', '')
      else receiptpath
    end,
    updatedat = now()
  where id = p_expenseid;

  delete from public.expense_shares where expenseid = p_expenseid;

  insert into public.expense_shares (expenseid, memberid, membertype, amount, sentat, confirmedat)
  select
    p_expenseid, s ->> 'memberid', s ->> 'membertype', (s ->> 'amount')::integer,
    o.sentat, o.confirmedat
  from jsonb_array_elements(payload -> 'shares') s
  left join lateral (
    select (x ->> 'sentat')::timestamptz as sentat,
           (x ->> 'confirmedat')::timestamptz as confirmedat
    from jsonb_array_elements(v_old) x
    where x ->> 'memberid' = s ->> 'memberid'
      and x ->> 'membertype' = s ->> 'membertype'
      and (x ->> 'amount')::integer = (s ->> 'amount')::integer
    limit 1
  ) o on true;
end;
$$;

-- service_role 만 실행 가능
revoke all on function public.assert_room_participant(bigint, text, text) from public, anon, authenticated;
revoke all on function public.create_expense(jsonb) from public, anon, authenticated;
revoke all on function public.update_expense(bigint, jsonb) from public, anon, authenticated;
grant execute on function public.assert_room_participant(bigint, text, text) to service_role;
grant execute on function public.create_expense(jsonb) to service_role;
grant execute on function public.update_expense(bigint, jsonb) to service_role;

