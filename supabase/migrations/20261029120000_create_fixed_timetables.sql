-- 고정 시간표 (마이페이지)
--   * 요일별로 반복되는 "못 하는 시간"(수업, 알바 등)을 저장한다.
--   * 방 시간표에서 가능한 시간을 고를 때, 여기 등록된 시간을 뺀 칸이 미리 채워진다.
--   * 회원 본인 것만 읽고 쓴다. (게스트는 Supabase 로그인이 없어서 사용 불가)

create table if not exists public.fixed_timetables (
  id bigint generated by default as identity primary key,
  userid uuid not null references auth.users (id) on delete cascade,
  weekday smallint not null check (weekday between 0 and 6),   -- 0=일 ... 6=토 (JS getDay 기준)
  starttime time not null,
  endtime time not null,
  createdat timestamptz not null default now(),
  check (endtime > starttime)
);

create index if not exists fixed_timetables_userid_idx
  on public.fixed_timetables (userid, weekday);

alter table public.fixed_timetables enable row level security;

create policy "fixed_timetables_select_own" on public.fixed_timetables
  for select using (auth.uid() = userid);

create policy "fixed_timetables_insert_own" on public.fixed_timetables
  for insert with check (auth.uid() = userid);

create policy "fixed_timetables_delete_own" on public.fixed_timetables
  for delete using (auth.uid() = userid);
