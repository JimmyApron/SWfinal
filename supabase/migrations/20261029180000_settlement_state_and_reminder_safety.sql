  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expenseid bigint NOT NULL REFERENCES public.expenses(id) ON DELETE CASCADE,
  originalshareid bigint,
  memberid text NOT NULL,
  membertype text NOT NULL CHECK (membertype IN ('member', 'guest')),
  amount integer NOT NULL,
  sentat timestamptz,
  confirmedat timestamptz,
  sentamount integer,
  confirmedamount integer,
  changeat timestamptz NOT NULL DEFAULT now()
