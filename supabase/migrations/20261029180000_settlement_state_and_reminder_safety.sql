-- Preserve transfer history across edits and serialize settlement transitions.
ALTER TABLE public.expense_shares
  ADD COLUMN IF NOT EXISTS sentamount integer,
  ADD COLUMN IF NOT EXISTS confirmedamount integer,
  ADD COLUMN IF NOT EXISTS reconfirmrequired boolean NOT NULL DEFAULT false;

UPDATE public.expense_shares
SET sentamount = CASE WHEN sentat IS NOT NULL THEN amount ELSE NULL END,
    confirmedamount = CASE WHEN confirmedat IS NOT NULL THEN amount ELSE NULL END
WHERE sentamount IS NULL OR confirmedamount IS NULL;

CREATE TABLE IF NOT EXISTS public.settlement_reminder_deliveries (
  expenseid bigint NOT NULL REFERENCES public.expenses(id) ON DELETE CASCADE,
  membertype text NOT NULL CHECK (membertype IN ('member', 'guest')),
  memberid text NOT NULL,
  last_sent_at timestamptz NOT NULL,
  PRIMARY KEY (expenseid, membertype, memberid)
);
ALTER TABLE public.settlement_reminder_deliveries ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.settlement_reminder_deliveries TO service_role;

