CREATE OR REPLACE FUNCTION public.update_expense(p_expenseid bigint, payload jsonb)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_expense public.expenses%rowtype;
  v_amount integer := (payload ->> 'amount')::integer;
  v_share jsonb;
  v_sum bigint := 0;
BEGIN
  SELECT * INTO v_expense FROM public.expenses
  WHERE id = p_expenseid AND isdeleted = false FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'expense % not found', p_expenseid; END IF;
  IF v_amount IS NULL OR v_amount <= 0 THEN RAISE EXCEPTION 'amount must be a positive integer'; END IF;
  IF jsonb_typeof(payload -> 'shares') IS DISTINCT FROM 'array'
     OR jsonb_array_length(payload -> 'shares') = 0 THEN
    RAISE EXCEPTION 'at least one share is required';
  END IF;
  PERFORM public.assert_room_participant(v_expense.roomid, payload ->> 'payerid', payload ->> 'payertype');
  FOR v_share IN SELECT * FROM jsonb_array_elements(payload -> 'shares') LOOP
    PERFORM public.assert_room_participant(v_expense.roomid, v_share ->> 'memberid', v_share ->> 'membertype');
    v_sum := v_sum + (v_share ->> 'amount')::integer;
  END LOOP;
  IF v_sum <> v_amount THEN RAISE EXCEPTION 'shares total (%) does not match amount (%)', v_sum, v_amount; END IF;

  INSERT INTO public.expense_share_history(
    expenseid, originalshareid, memberid, membertype, amount,
    sentat, confirmedat, sentamount, confirmedamount
  )
  SELECT old.expenseid, old.id, old.memberid, old.membertype, old.amount,
    old.sentat, old.confirmedat, old.sentamount, old.confirmedamount
  FROM public.expense_shares old
  WHERE old.expenseid = p_expenseid
    AND (old.sentat IS NOT NULL OR old.confirmedat IS NOT NULL)
    AND NOT EXISTS (
      SELECT 1 FROM jsonb_array_elements(payload -> 'shares') s
      WHERE s ->> 'memberid' = old.memberid AND s ->> 'membertype' = old.membertype
        AND (s ->> 'amount')::integer = old.amount
    );

  UPDATE public.expenses SET
    title = payload ->> 'title', amount = v_amount,
    paidat = nullif(payload ->> 'paidat', '')::timestamptz,
    payerid = payload ->> 'payerid', payertype = payload ->> 'payertype',
    bankname = nullif(payload ->> 'bankname', ''),
    accountnumber = nullif(payload ->> 'accountnumber', ''),
    splitmode = coalesce(payload ->> 'splitmode', splitmode),
    receiptpath = CASE WHEN payload ? 'receiptpath' THEN nullif(payload ->> 'receiptpath', '') ELSE receiptpath END,
    updatedat = now()
  WHERE id = p_expenseid;

  -- Keep transfer and receipt timestamps as history. Amount snapshots make a
  -- changed share explicitly unconfirmed until the payer confirms the new amount.
  INSERT INTO public.expense_shares(
    expenseid, memberid, membertype, amount, sentat, confirmedat,
    sentamount, confirmedamount, reconfirmrequired
  )
  SELECT p_expenseid, s ->> 'memberid', s ->> 'membertype', (s ->> 'amount')::integer,
    old.sentat, old.confirmedat, old.sentamount, old.confirmedamount,
    (coalesce(old.reconfirmrequired, false) OR
      (old.id IS NOT NULL AND (old.sentat IS NOT NULL OR old.confirmedat IS NOT NULL)
        AND old.amount <> (s ->> 'amount')::integer))
  FROM jsonb_array_elements(payload -> 'shares') s
  LEFT JOIN public.expense_shares old ON old.expenseid = p_expenseid
    AND old.memberid = s ->> 'memberid' AND old.membertype = s ->> 'membertype'
  ON CONFLICT (expenseid, membertype, memberid) DO UPDATE SET
    amount = EXCLUDED.amount, sentat = EXCLUDED.sentat, confirmedat = EXCLUDED.confirmedat,
    sentamount = EXCLUDED.sentamount, confirmedamount = EXCLUDED.confirmedamount,
    reconfirmrequired = EXCLUDED.reconfirmrequired;

  DELETE FROM public.expense_shares old
  WHERE old.expenseid = p_expenseid
    AND NOT EXISTS (
      SELECT 1 FROM jsonb_array_elements(payload -> 'shares') s
      WHERE old.memberid = s ->> 'memberid' AND old.membertype = s ->> 'membertype'
    );
  DELETE FROM public.settlement_reminder_deliveries WHERE expenseid = p_expenseid;
END;
$$;

-- Atomic sent/confirm state transitions. The expense row lock serializes
-- simultaneous confirmation requests and prevents transitions after deletion.
CREATE OR REPLACE FUNCTION public.transition_expense_share(
  p_expenseid bigint, p_memberid text, p_membertype text,
  p_actorid text, p_actortype text, p_action text, p_value boolean
) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE
  v_expense public.expenses%rowtype;
  v_share public.expense_shares%rowtype;
  v_changed boolean := false;
  v_complete boolean := false;
  v_was_complete boolean := false;
BEGIN
  SELECT * INTO v_expense FROM public.expenses WHERE id = p_expenseid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'expense not found'; END IF;
  IF v_expense.isdeleted THEN RAISE EXCEPTION 'expense not found'; END IF;
  PERFORM public.assert_room_participant(v_expense.roomid, p_actorid, p_actortype);
  PERFORM public.assert_room_participant(v_expense.roomid, p_memberid, p_membertype);
  SELECT * INTO v_share FROM public.expense_shares
    WHERE expenseid = p_expenseid AND memberid = p_memberid AND membertype = p_membertype FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'share not found'; END IF;
  IF v_share.amount <= 0 THEN RAISE EXCEPTION 'share not found'; END IF;

  SELECT NOT EXISTS (
    SELECT 1 FROM public.expense_shares s WHERE s.expenseid = p_expenseid
      AND (s.membertype, s.memberid) <> (v_expense.payertype, v_expense.payerid)
      AND s.amount > 0
      AND (s.confirmedat IS NULL OR s.confirmedamount IS DISTINCT FROM s.amount OR s.reconfirmrequired)
  ) INTO v_was_complete;

  IF p_action = 'sent' THEN
    IF (p_membertype, p_memberid) = (v_expense.payertype, v_expense.payerid) THEN RAISE EXCEPTION 'payer has no share to send'; END IF;
    IF (p_actorid, p_actortype) <> (p_memberid, p_membertype) THEN RAISE EXCEPTION 'only the share owner can mark sent'; END IF;
    IF p_value THEN
      IF v_share.sentat IS NULL OR v_share.sentamount IS DISTINCT FROM v_share.amount THEN
        UPDATE public.expense_shares SET sentat = now(), sentamount = amount WHERE id = v_share.id;
        v_changed := true;
      END IF;
    ELSE
      IF v_share.confirmedat IS NOT NULL AND v_share.confirmedamount = v_share.amount AND NOT v_share.reconfirmrequired THEN
        RAISE EXCEPTION 'confirmed transfer cannot be undone';
      END IF;
      IF v_share.sentat IS NOT NULL THEN
        UPDATE public.expense_shares SET sentat = NULL, sentamount = NULL WHERE id = v_share.id;
        v_changed := true;
      END IF;
    END IF;
  ELSIF p_action = 'confirm' THEN
    IF (p_actorid, p_actortype) <> (v_expense.payerid, v_expense.payertype) THEN RAISE EXCEPTION 'only payer can confirm'; END IF;
    IF (p_memberid, p_membertype) = (v_expense.payerid, v_expense.payertype) THEN RAISE EXCEPTION 'payer cannot confirm own share'; END IF;
    IF p_value THEN
      IF v_share.sentat IS NULL OR v_share.sentamount IS DISTINCT FROM v_share.amount THEN RAISE EXCEPTION 'share is not marked as sent'; END IF;
      IF v_share.confirmedat IS NULL OR v_share.confirmedamount IS DISTINCT FROM v_share.amount OR v_share.reconfirmrequired THEN
        UPDATE public.expense_shares SET confirmedat = now(), confirmedamount = amount, reconfirmrequired = false WHERE id = v_share.id;
        v_changed := true;
      END IF;
    ELSE
      IF v_share.confirmedat IS NOT NULL AND v_share.confirmedamount = v_share.amount AND NOT v_share.reconfirmrequired THEN
        UPDATE public.expense_shares SET confirmedat = NULL, confirmedamount = NULL WHERE id = v_share.id;
        v_changed := true;
      END IF;
    END IF;
  ELSE
    RAISE EXCEPTION 'invalid transition';
  END IF;

  SELECT NOT EXISTS (
    SELECT 1 FROM public.expense_shares s WHERE s.expenseid = p_expenseid
      AND (s.membertype, s.memberid) <> (v_expense.payertype, v_expense.payerid)
      AND s.amount > 0
      AND (s.confirmedat IS NULL OR s.confirmedamount IS DISTINCT FROM s.amount OR s.reconfirmrequired)
  ) INTO v_complete;
  RETURN jsonb_build_object('changed', v_changed, 'complete', v_complete, 'became_complete', v_changed AND v_complete AND NOT v_was_complete);
END;
$$;

-- Atomically claim only currently unpaid positive shares; one member/guest
-- identity has a six hour cooldown regardless of duplicate HTTP requests.
CREATE OR REPLACE FUNCTION public.claim_settlement_reminders(p_expenseid bigint, p_targets jsonb)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE
  v_expense public.expenses%rowtype;
  v_target jsonb;
  v_claimed jsonb := '[]'::jsonb;
  v_id text;
  v_type text;
BEGIN
  SELECT * INTO v_expense FROM public.expenses WHERE id = p_expenseid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'expense not found'; END IF;
  IF v_expense.isdeleted THEN RAISE EXCEPTION 'expense not found'; END IF;
  FOR v_target IN SELECT * FROM jsonb_array_elements(coalesce(p_targets, '[]'::jsonb)) LOOP
    v_id := v_target ->> 'memberid'; v_type := v_target ->> 'membertype';
    IF v_type NOT IN ('member','guest') OR (v_type, v_id) = (v_expense.payertype, v_expense.payerid) THEN CONTINUE; END IF;
    PERFORM public.assert_room_participant(v_expense.roomid, v_id, v_type);
    IF NOT EXISTS (SELECT 1 FROM public.expense_shares s WHERE s.expenseid=p_expenseid
      AND s.memberid=v_id AND s.membertype=v_type AND s.amount > 0
      AND (s.sentat IS NULL OR s.sentamount IS DISTINCT FROM s.amount)
      AND (s.confirmedat IS NULL OR s.confirmedamount IS DISTINCT FROM s.amount OR s.reconfirmrequired)) THEN CONTINUE; END IF;
    INSERT INTO public.settlement_reminder_deliveries AS delivery(expenseid,membertype,memberid,last_sent_at)
    VALUES(p_expenseid,v_type,v_id,now())
    ON CONFLICT(expenseid,membertype,memberid) DO UPDATE SET last_sent_at=now()
      WHERE delivery.last_sent_at < now() - interval '6 hours';
    IF FOUND THEN v_claimed := v_claimed || jsonb_build_array(jsonb_build_object('memberid',v_id,'membertype',v_type)); END IF;
  END LOOP;
  RETURN v_claimed;
END;
$$;

CREATE OR REPLACE FUNCTION public.soft_delete_expense(p_expenseid bigint)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_expense public.expenses%rowtype;
BEGIN
  SELECT * INTO v_expense FROM public.expenses WHERE id=p_expenseid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'expense not found'; END IF;
  IF v_expense.isdeleted THEN RAISE EXCEPTION 'expense not found'; END IF;
  UPDATE public.expenses SET isdeleted=true, updatedat=now() WHERE id=p_expenseid;
  DELETE FROM public.settlement_reminder_deliveries WHERE expenseid=p_expenseid;
END;
$$;

CREATE OR REPLACE FUNCTION public.release_settlement_reminders(p_expenseid bigint, p_targets jsonb)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_target jsonb;
BEGIN
  FOR v_target IN SELECT * FROM jsonb_array_elements(coalesce(p_targets, '[]'::jsonb)) LOOP
    DELETE FROM public.settlement_reminder_deliveries
    WHERE expenseid=p_expenseid
      AND membertype=(v_target ->> 'membertype')
      AND memberid=(v_target ->> 'memberid');
  END LOOP;
END;
$$;

